def compacta( mesg, tabela ):
    pos = len( tabela) - 1
    while pos >= 0 :
        tup = tabela[pos]
        dep = mesg + "  idx " + str(pos) + "  tup " + tup[1]
        #print( dep.encode('UTF-8'))
        mesg = mesg.replace( tup[1], tup[0])
        pos -= 1

    return mesg


def descompacta(mesg, tabela):
    pos = 0
    max = len( tabela)
    while pos < max :
        tup = tabela[pos]
        dep = mesg + "  idx " + str(pos) + "  tup " + tup[1]
        #print( dep.encode('UTF-8'))
        mesg = mesg.replace( tup[0], tup[1])
        pos += 1

    return mesg


